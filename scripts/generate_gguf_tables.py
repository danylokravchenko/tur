#!/usr/bin/env python3
"""Generate Tur's GGUF codebook tables from ggml's `ggml-common.h` (MIT, ggml authors).

    python3 scripts/generate_gguf_tables.py path/to/ggml-common.h

Writes `crates/tur-metal/src/block_tables.rs` for the host decoder and
`crates/tur-metal/src/kernels/block_tables.metal` for the device decoder, so both read the
same numbers. The Metal side splits 64-bit grid entries into two 32-bit words.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLES = {
    "ksigns_iq2xs": ("KSIGNS", 8),
    "kvalues_iq4nl": ("KVALUES_IQ4NL", 8),
    "kvalues_fp4": ("KVALUES_FP4", 8),
    "iq2xxs_grid": ("IQ2XXS_GRID", 64),
    "iq2xs_grid": ("IQ2XS_GRID", 64),
    "iq2s_grid": ("IQ2S_GRID", 64),
    "iq3xxs_grid": ("IQ3XXS_GRID", 32),
    "iq3s_grid": ("IQ3S_GRID", 32),
    "iq1s_grid": ("IQ1S_GRID", 64),
}
RUST_TYPE = {"KVALUES_IQ4NL": "i8", "KVALUES_FP4": "i8", "KSIGNS": "u8"}


def table(source: str, name: str) -> list[int]:
    match = re.search(rf"GGML_TABLE_BEGIN\(\w+, {name}, \w+\)(.*?)GGML_TABLE_END", source, re.S)
    if match is None:
        raise SystemExit(f"table {name} not found")
    # Comments in the header hold no numbers worth keeping.
    body = re.sub(r"//.*", "", match.group(1))
    return [int(value, 0) for value in re.findall(r"-?0x[0-9A-Fa-f]+|-?\d+", body)]


def wrap(values: list[str], per_line: int = 8) -> str:
    return "\n".join(
        "    " + ", ".join(values[i : i + per_line]) + ","
        for i in range(0, len(values), per_line)
    )


def main() -> None:
    source = Path(sys.argv[1]).read_text()
    rust = [
        "//! Generated by `scripts/generate_gguf_tables.py` from ggml's `ggml-common.h` (MIT).",
        "#![allow(clippy::unreadable_literal, reason = \"generated tables\")]",
        "",
    ]
    metal = [
        "// Generated by scripts/generate_gguf_tables.py from ggml's ggml-common.h (MIT).",
        "",
    ]
    for name, (constant, bits) in TABLES.items():
        values = table(source, name)
        kind = RUST_TYPE.get(constant, f"u{bits}")
        rust.append(f"pub(crate) const {constant}: [{kind}; {len(values)}] = [")
        rust.append(wrap([str(v) if bits == 8 else f"0x{v:x}" for v in values]))
        rust.extend(["];", ""])
        if bits == 64:
            words = [f"0x{w:x}u" for v in values for w in (v & 0xFFFFFFFF, v >> 32)]
            metal.append(f"constant uint {constant}[{2 * len(values)}] = {{")
        elif bits == 32:
            words = [f"0x{v:x}u" for v in values]
            metal.append(f"constant uint {constant}[{len(values)}] = {{")
        else:
            words = [str(v) for v in values]
            metal.append(f"constant {'char' if kind == 'i8' else 'uchar'} {constant}[{len(values)}] = {{")
        metal.append(wrap(words))
        metal.extend(["};", ""])
    (ROOT / "crates/tur-metal/src/block_tables.rs").write_text("\n".join(rust))
    (ROOT / "crates/tur-metal/src/kernels/block_tables.metal").write_text("\n".join(metal))


if __name__ == "__main__":
    main()
